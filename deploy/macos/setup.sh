#!/usr/bin/env bash
# Pithagoras on macOS (Apple Silicon): portal in Docker, models in oMLX.
#
#   deploy/macos/setup.sh            # create .env if missing, build, start, configure pi
#   deploy/macos/setup.sh --force    # also overwrite pi's models.json / settings.json
#
# Safe to run again. See docs/guide/macos.md.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
HERE="$ROOT/deploy/macos"
FORCE=false
[ "${1:-}" = "--force" ] && FORCE=true

compose() { docker compose -f "$ROOT/docker-compose.yml" -f "$ROOT/docker-compose.macos.yml" "$@"; }
say() { printf '\033[1m==> %s\033[0m\n' "$*"; }
fail() { printf '\033[31mError:\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(uname -s)" = "Darwin" ] || fail "This script is for macOS."
command -v docker >/dev/null || fail "Docker is not installed. Install OrbStack (brew install orbstack)."
docker info >/dev/null 2>&1 || fail "Docker is not running. Start OrbStack (orbctl start)."

# Host networking has to share localhost with the Mac, or neither oMLX nor the
# portal is reachable. OrbStack does that out of the box; Docker Desktop only
# with Settings → Resources → Network → Enable host networking.
context="$(docker context show 2>/dev/null || true)"
if [ "$context" != "orbstack" ]; then
  echo "Note: Docker context is '$context', not 'orbstack'. Docker Desktop needs host networking enabled."
fi

cd "$ROOT"

if [ ! -f .env ]; then
  say "Creating .env"
  omlx_key=""
  if [ -r "$HOME/.omlx/settings.json" ]; then
    omlx_key="$(python3 -c 'import json,os;print(json.load(open(os.path.expanduser("~/.omlx/settings.json"))).get("auth",{}).get("api_key") or "")' 2>/dev/null || true)"
  fi
  cat > .env <<EOF
# Generated by deploy/macos/setup.sh — see docs/guide/macos.md
# No password here: the portal asks for one the first time it is opened.
PORTAL_SECRET=$(openssl rand -hex 32)
PORTAL_HOST=127.0.0.1
WORKSPACES_DIR=$HOME/Pithagoras/workspaces
EXECUTOR=host
# Left empty so pi's settings.json (defaultProvider/defaultModel) decides.
PI_PROVIDER=
PI_MODEL=
OMLX_API_KEY=$omlx_key
EOF
  chmod 600 .env
fi

set -a; . ./.env; set +a
mkdir -p "${WORKSPACES_DIR:-$HOME/Pithagoras/workspaces}"

say "Checking oMLX"
code="$(curl -s -o /dev/null -w '%{http_code}' -m 5 -H "Authorization: Bearer ${OMLX_API_KEY:-}" http://127.0.0.1:8000/v1/models || true)"
case "$code" in
  200) echo "oMLX reachable." ;;
  401|403) fail "oMLX rejected OMLX_API_KEY. Set it in .env (oMLX → Settings → API key)." ;;
  *) echo "Warning: oMLX not reachable on 127.0.0.1:8000 (HTTP $code). Start oMLX; the portal will still start." ;;
esac

say "Building and starting the portal"
compose up -d --build

say "Configuring pi (provider omlx)"
agent_dir=/data/home/.pi/agent
compose exec -T portal mkdir -p "$agent_dir"
for pair in "pi-models.json:models.json" "pi-settings.json:settings.json"; do
  src="${pair%%:*}"; dst="${pair##*:}"
  if $FORCE || ! compose exec -T portal test -s "$agent_dir/$dst"; then
    compose cp "$HERE/$src" "portal:$agent_dir/$dst"
    echo "Installed $dst"
  else
    echo "Kept existing $dst (use --force to overwrite)"
  fi
done

port="${PORT:-4100}"
say "Waiting for http://localhost:$port"
for _ in $(seq 1 30); do
  if curl -s -m 2 "http://127.0.0.1:$port/api/auth/status" >/dev/null; then
    echo "Pithagoras is up: http://localhost:$port"
    echo "The first visit asks you to choose the portal's password."
    exit 0
  fi
  sleep 2
done
fail "The portal did not answer. Check: docker compose -f docker-compose.yml -f docker-compose.macos.yml logs portal"
